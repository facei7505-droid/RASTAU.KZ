import { useState, useEffect } from 'preact/hooks'

// Язык интерфейса (государственный и русский), общий для всех экранов
let LANG = (() => { try { return localStorage.getItem('fakt-lang') || 'ru' } catch { return 'ru' } })()
const langSubs = new Set()
export const tr = (ru, kz) => (LANG === 'kz' ? kz : ru)
export const useLang = () => {
  const [lang, setLang] = useState(LANG)
  useEffect(() => { langSubs.add(setLang); return () => langSubs.delete(setLang) }, [])
  const set = (l) => { LANG = l; try { localStorage.setItem('fakt-lang', l) } catch {} ; document.documentElement.lang = l === 'kz' ? 'kk' : 'ru'; langSubs.forEach((f) => f(l)) }
  return [lang, set, (ru, kz) => (lang === 'kz' ? kz : ru)]
}

